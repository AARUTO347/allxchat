const BoardInfo* aruGetAllBoards() {
    return aru_board_list[0] ? aru_board_list : nullptr;
}

const size_t aruGetBoardCount() {
    size_t count = 0;
    while (aru_board_list[count] != nullptr) {
        count++;
    }
    return count;
}

const BoardInfo* aruFindBoard(const char* name) {
    if (name == nullptr) return nullptr;

    for (size_t i = 0; aru_board_list[i] != nullptr; i++) {
        if (strcmp(aru_board_list[i]->name, name) == 0) {
            return aru_board_list[i];
        }
    }

    // Case-insensitive fallback
    size_t nameLen = strlen(name);
    for (size_t i = 0; aru_board_list[i] != nullptr; i++) {
        const char* bname = aru_board_list[i]->name;
        if (strlen(bname) == nameLen) {
            bool match = true;
            for (size_t j = 0; j < nameLen; j++) {
                char a = bname[j];
                char b = name[j];
                if (a >= 'a' && a <= 'z') a -= 32;
                if (b >= 'a' && b <= 'z') b -= 32;
                if (a != b) { match = false; break; }
            }
            if (match) return aru_board_list[i];
        }
    }
    return nullptr;
}

std::vector<std::string> aruListBoards() {
    std::vector<std::string> names;
    for (size_t i = 0; aru_board_list[i] != nullptr; i++) {
        if (aru_board_list[i]->name) {
            names.push_back(aru_board_list[i]->name);
        }
    }
    return names;
}